"""Search GitHub for candidate resources that may belong in the catalog.

This script is intentionally conservative: it produces a review report, not an
automatic catalog update. A human curator should inspect each candidate, verify
its relevance to bubble dynamics or boiling, and then add accepted entries to
data/resources.csv. The report also includes manual web/archive search prompts
so discovery does not stay biased toward GitHub-visible code when the catalog's
largest remaining gaps are often dataset and archive entries.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys
import urllib.parse
import urllib.request
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
QUERY_FILE = ROOT / "data" / "discovery_queries.json"
CATALOG_FILE = ROOT / "data" / "resources.csv"


def github_get(url: str) -> dict:
    headers = {
        "Accept": "application/vnd.github+json",
        "User-Agent": "bubble-dynamics-catalog-discovery",
    }
    token = os.getenv("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.loads(response.read().decode("utf-8"))


def load_queries() -> list[dict[str, str]]:
    with QUERY_FILE.open(encoding="utf-8") as handle:
        payload = json.load(handle)
    return payload


def load_catalog() -> list[dict[str, str]]:
    with CATALOG_FILE.open(newline="", encoding="utf-8") as handle:
        return [dict(row) for row in csv.DictReader(handle)]


def search_github(query: str, sort: str, per_page: int) -> list[dict]:
    params = urllib.parse.urlencode({"q": query, "sort": sort, "order": "desc", "per_page": per_page})
    url = f"https://api.github.com/search/repositories?{params}"
    return github_get(url).get("items", [])


def discovery_gap_rows(rows: list[dict[str, str]], limit: int = 8) -> list[dict[str, str]]:
    candidates: list[dict[str, str]] = []
    for row in rows:
        if row["status"] == "adjacent":
            continue
        missing_paper = not row["paper_url"].strip()
        generic_license = row["license"] in {
            "Repository license",
            "Open-source project terms",
            "Project terms",
            "GPL-compatible project terms",
        }
        if not (missing_paper or generic_license):
            continue
        score = 0
        if "Reduced-order bubble dynamics" in row["category"]:
            score += 4
        if "Datasets" in row["category"]:
            score += 3
        if missing_paper:
            score += 2
        if generic_license:
            score += 1
        candidates.append(
            {
                "name": row["name"],
                "url": row["url"],
                "category": row["category"],
                "license": row["license"],
                "paper_url": row["paper_url"],
                "source_checked": row["source_checked"],
                "score": str(score),
            }
        )
    candidates.sort(key=lambda item: (-int(item["score"]), item["source_checked"], item["name"].lower()))
    return candidates[:limit]


def render_report(per_page: int) -> str:
    payload = load_queries()
    catalog = load_catalog()
    lines = [
        "# Discovery Candidates",
        "",
        "This report is generated by `scripts/discover_candidates.py`. It is a triage aid, not an endorsement.",
        "",
    ]
    for query in payload["github"]:
        lines.extend([f"## {query['name']}", "", f"Query: `{query['query']}`", "", "| Repository | Description | Stars | Updated | License | Topics |", "| --- | --- | ---: | --- | --- | --- |"])
        try:
            items = search_github(query["query"], query.get("sort", "updated"), per_page)
        except Exception as exc:  # pragma: no cover - report generation should be resilient.
            lines.extend(
                [
                    f"Search unavailable in this environment: `{exc}`",
                    "",
                    "Use the manual search seeds below, then update `data/resources.csv` only after source verification.",
                    "",
                ]
            )
            continue
        for item in items:
            license_info = item.get("license") or {}
            topics = ", ".join(item.get("topics", [])[:8])
            description = (item.get("description") or "").replace("|", "\\|")
            lines.append(
                f"| [{item['full_name']}]({item['html_url']}) | {description} | {item['stargazers_count']} | {item['updated_at'][:10]} | {license_info.get('spdx_id', '')} | {topics} |"
            )
        lines.append("")

    lines.extend(
        [
            "## Gap-Targeted Priorities",
            "",
            "These rows come from the current catalog itself, so the discovery report stays useful even when live GitHub search is blocked. Prioritize them when you want the next maintenance pass to reduce repeated review comments instead of expanding already-strong categories.",
            "",
            "| Current gap row | Category | Missing paper link | Generic license label | Last checked |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for row in discovery_gap_rows(catalog):
        lines.append(
            f"| [{row['name']}]({row['url']}) | {row['category']} | {'yes' if not row['paper_url'] else 'no'} | {'yes' if row['license'] in {'Repository license', 'Open-source project terms', 'Project terms', 'GPL-compatible project terms'} else 'no'} | {row['source_checked']} |"
        )
    lines.append("")

    lines.extend(
        [
            "## Manual Web Search Seeds",
            "",
            "Use these prompts when GitHub alone would miss papers, datasets, or institutional-hosted tools.",
            "",
            "| Prompt |",
            "| --- |",
        ]
    )
    for query in payload.get("web", []):
        lines.append(f"| `{query}` |")
    lines.append("")

    lines.extend(
        [
            "## Manual Archive Search Seeds",
            "",
            "Use these prompts for Dryad, Mendeley Data, Dataverse, Hugging Face, NASA DASHlink, Zenodo, and similar archive-first maintenance passes.",
            "",
            "| Prompt |",
            "| --- |",
        ]
    )
    for query in payload.get("archives", []):
        lines.append(f"| `{query}` |")
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--per-page", type=int, default=10, help="Number of GitHub results per query.")
    parser.add_argument("--output", type=Path, default=None, help="Optional path for a markdown report.")
    args = parser.parse_args()

    report = render_report(args.per_page)
    if args.output:
        output = args.output if args.output.is_absolute() else ROOT / args.output
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(report, encoding="utf-8")
    else:
        sys.stdout.write(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
