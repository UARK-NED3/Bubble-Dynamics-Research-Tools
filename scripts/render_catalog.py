def is_dataset_like(row: dict[str, str]) -> bool:
    return row["kind"] in {"Dataset", "Code and dataset"}


def dataset_readiness(row: dict[str, str]) -> str:
    if row["status"] == "review sharing" or scope_alignment(row) == "Peripheral or transfer-only":
        return "Access-risky transfer dataset"

    paper_state = paper_evidence_status(row)
    if paper_state == "Direct paper link" and scope_alignment(row) == "Core bubble/boiling":
        return "Benchmark-ready"
    if paper_state == "Direct paper link":
        return "Paper-backed archive"
    if paper_state != "No public paper evidence surfaced":
        return "Citation-verified dataset"
    return "Archive-only discovery lead"


def dataset_snapshot(rows: Iterable[dict[str, str]]) -> list[dict[str, str]]:
    readiness_order = {
        "Benchmark-ready": 0,
        "Paper-backed archive": 1,
        "Citation-verified dataset": 2,
        "Archive-only discovery lead": 3,
        "Access-risky transfer dataset": 4,
    }
    snapshot: list[dict[str, str]] = []
    for row in active_rows(rows):
        if not is_dataset_like(row):
            continue
        snapshot.append(
            {
                "resource": markdown_link(row),
                "category": base_category(row["category"]),
                "paper_evidence": paper_evidence_status(row),
                "license_bucket": license_bucket(row),
                "readiness": dataset_readiness(row),
                "last_checked": row["source_checked"],
            }
        )
    snapshot.sort(
        key=lambda item: (
            readiness_order.get(item["readiness"], 99),
            item["category"].lower(),
            item["resource"].lower(),
        )
    )
    return snapshot


def dataset_readiness_counts(rows: Iterable[dict[str, str]]) -> list[tuple[str, int]]:
    counts: Counter[str] = Counter()
    for row in active_rows(rows):
        if is_dataset_like(row):
            counts[dataset_readiness(row)] += 1
    order = {
        "Benchmark-ready": 0,
        "Paper-backed archive": 1,
        "Citation-verified dataset": 2,
        "Archive-only discovery lead": 3,
        "Access-risky transfer dataset": 4,
    }
    return sorted(counts.items(), key=lambda item: (order.get(item[0], 99), item[0]))


