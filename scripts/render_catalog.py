def scope_alignment_counts(rows: Iterable[dict[str, str]]) -> list[tuple[str, int]]:
    counts: Counter[str] = Counter()
    for row in active_rows(rows):
        counts[scope_alignment(row)] += 1
    order = {
        "Core bubble/boiling": 0,
        "Adjacent but directly useful": 1,
        "Peripheral or transfer-only": 2,
        "Name-collision guardrail": 3,
    }
    return sorted(counts.items(), key=lambda item: (order.get(item[0], 99), item[0]))


def paper_evidence_counts(rows: Iterable[dict[str, str]]) -> list[tuple[str, int]]:
    counts: Counter[str] = Counter()
    for row in active_rows(rows):
        if row["kind"] not in {"Code", "Code and dataset", "Dataset", "Model artifact"}:
            continue
        counts[paper_evidence_status(row)] += 1
    order = {
        "Direct paper link": 0,
        "Citation text verified, URL unresolved": 1,
        "Project citation database only": 2,
        "No public paper evidence surfaced": 3,
    }
    return sorted(counts.items(), key=lambda item: (order.get(item[0], 99), item[0]))


def paper_evidence_by_category(rows: Iterable[dict[str, str]]) -> list[dict[str, object]]:
    grouped: dict[str, Counter[str]] = defaultdict(Counter)
    evidence_order = [
        "Direct paper link",
        "Citation text verified, URL unresolved",
        "Project citation database only",
        "No public paper evidence surfaced",
    ]
    for row in active_rows(rows):
        if row["kind"] not in {"Code", "Code and dataset", "Dataset", "Model artifact"}:
            continue
        grouped[base_category(row["category"])][paper_evidence_status(row)] += 1

    results: list[dict[str, object]] = []
    for category, counts in grouped.items():
        total = sum(counts.values())
        results.append(
            {
                "category": category,
                "total": total,
                "counts": {evidence: counts.get(evidence, 0) for evidence in evidence_order},
            }
        )
    return sorted(results, key=lambda item: (-int(item["total"]), str(item["category"])))


def scope_alignment_by_category(rows: Iterable[dict[str, str]]) -> list[dict[str, object]]:
    grouped: dict[str, Counter[str]] = defaultdict(Counter)
    scope_order = [
        "Core bubble/boiling",
        "Adjacent but directly useful",
        "Peripheral or transfer-only",
    ]
    for row in active_rows(rows):
        grouped[base_category(row["category"])][scope_alignment(row)] += 1

    results: list[dict[str, object]] = []
    for category, counts in grouped.items():
        total = sum(counts.values())
        results.append(
            {
                "category": category,
                "total": total,
                "counts": {scope: counts.get(scope, 0) for scope in scope_order},
            }
        )
    return sorted(results, key=lambda item: (-int(item["total"]), str(item["category"])))


def active_rows(rows: Iterable[dict[str, str]]) -> list[dict[str, str]]:
    return [row for row in rows if row["status"] != "adjacent"]


