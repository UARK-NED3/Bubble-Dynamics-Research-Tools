def load_rows() -> list[dict[str, str]]:
    with CATALOG.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        rows = [dict(row) for row in reader]
    validate(rows, reader.fieldnames or [])
    return rows


def validate(rows: list[dict[str, str]], fieldnames: list[str]) -> None:
    missing = REQUIRED_COLUMNS.difference(fieldnames)
    if missing:
        raise ValueError(f"Missing catalog columns: {sorted(missing)}")
    if not rows:
        raise ValueError("Catalog is empty.")

    seen: set[str] = set()
    for row in rows:
        identifier = row["id"].strip()
        if not identifier:
            raise ValueError("Catalog row has a blank id.")
        if identifier in seen:
            raise ValueError(f"Duplicate catalog id: {identifier}")
        seen.add(identifier)

        try:
            int(row["year"])
        except ValueError as exc:
            raise ValueError(f"Catalog id {identifier} has nonnumeric year.") from exc
        try:
            checked = date.fromisoformat(row["source_checked"])
        except ValueError as exc:
            raise ValueError(f"Catalog id {identifier} has invalid source_checked date.") from exc
        if checked > date.today():
            raise ValueError(f"Catalog id {identifier} has a future source_checked date.")

        for key in ("name", "kind", "category", "workflow", "url", "source_checked"):
            if not row[key].strip():
                raise ValueError(f"Catalog id {identifier} has blank {key}.")
        if not row["url"].startswith(("https://", "http://")):
            raise ValueError(f"Catalog id {identifier} has a non-web URL: {row['url']}")


def base_category(category: str) -> str:
    return category.split(" - ", 1)[0]


def markdown_link(row: dict[str, str]) -> str:
    return f"[{row['name']}]({row['url']})"


def rows_by_id(rows: Iterable[dict[str, str]]) -> dict[str, dict[str, str]]:
    return {row["id"]: row for row in rows}


def split_semicolon(value: str) -> list[str]:
    return [item.strip() for item in value.split(";") if item.strip()]


def has_link(value: str) -> bool:
    return bool(value.strip())


def grouped_rows(rows: Iterable[dict[str, str]]) -> dict[str, list[dict[str, str]]]:
    groups: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        groups[row["category"]].append(row)
    return dict(sorted(groups.items(), key=lambda item: item[0].lower()))


def render_catalog_markdown(rows: list[dict[str, str]]) -> str:
    lines = [
        "# Resource Catalog",
        "",
        "<!-- Generated by scripts/render_catalog.py from data/resources.csv. Do not edit this file by hand. -->",
        "",
        f"Resources: {len(rows)}. Source table: [`data/resources.csv`](../data/resources.csv).",
        "",
        "The catalog is grouped by practical research workflow rather than by publication chronology. Each entry should be checked in its own documentation before being used for quantitative claims.",
        "",
    ]

    for category, items in grouped_rows(rows).items():
        lines.extend(
            [
                f"## {category}",
                "",
                "| Resource | Kind | Regime | Modality | Workflow | Stack | Year | Status | Notes |",
                "| --- | --- | --- | --- | --- | --- | ---: | --- | --- |",
            ]
        )
        for row in sorted(items, key=lambda item: item["name"].lower()):
            lines.append(
                "| "
                + " | ".join(
                    [
                        markdown_link(row),
                        row["kind"],
                        row["regime"],
                        row["modality"],
                        row["workflow"],
                        row["stack"],
                        row["year"],
                        row["status"],
                        row["notes"],
                    ]
                )
                + " |"
            )
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def modality_tags(row: dict[str, str]) -> set[str]:
    text = " ".join([row["modality"], row["workflow"], row["notes"]]).lower()
    tags: set[str] = set()
    if any(word in text for word in ["optical", "image", "video", "vision", "frame"]):
        tags.add("Optical/video")
    if any(word in text for word in ["hydrophone", "audio", "microphone"]):
        tags.add("Acoustic")
    if "acoustic emission" in text or "ae " in f" {text} " or "ae;" in text:
        tags.add("AE")
    if any(word in text for word in ["temperature", "thermal", "thermocouple", "ir ", "flir"]):
        tags.add("Thermal/IR")
    if any(word in text for word in ["cfd", "vof", "hdf5", "field", "simulation"]):
        tags.add("Simulation fields")
    if any(word in text for word in ["mask", "annotation", "label", "contour"]):
        tags.add("Labels/masks")
    if any(word in text for word in ["ode", "rayleigh", "keller"]):
        tags.add("Reduced-order states")
    if any(word in text for word in ["piv", "centroid", "tracking", "trajectory"]):
        tags.add("Tracking/PIV")
    return tags or {"Other"}


def evidence_tier(row: dict[str, str]) -> str:
    has_repo = has_link(row["repository_url"])
    has_data = has_link(row["data_url"])
    has_paper = has_link(row["paper_url"])

    if has_repo and has_data and has_paper:
        return "Code + data + paper"
    if row["kind"] == "Dataset" and has_data and has_paper:
        return "Dataset + paper"
    if has_repo and (has_paper or row["kind"] in {"Documentation", "Example"}):
        return "Code + paper/docs"
    return "Partial link coverage"


def license_bucket(row: dict[str, str]) -> str:
    license_name = row["license"].strip()
    normalized = license_name.upper().replace("_", "-")
    if any(marker in normalized for marker in RESTRICTIVE_CC_MARKERS):
        return "Explicit restrictive terms"
    if any(marker in normalized for marker in OPEN_CC_MARKERS):
        return "Explicit open license"
    if any(token in license_name for token in OPEN_LICENSE_TOKENS):
        return "Explicit open license"
    if "non-commercial" in license_name.lower():
        return "Source-available non-commercial"
    if license_name in {"Archive terms", "Dataset terms", "Model terms"}:
        return "Archive/model terms"
    if license_name in {
        "Repository license",
        "Project terms",
        "Open-source project terms",
        "GPL-compatible project terms",
        "Documentation terms",
    }:
        return "Manual license review"
    if license_name == "NOASSERTION":
        return "Unclear license"
    return "Other terms"


def documentation_license_context(row: dict[str, str]) -> bool:
    if row["kind"] != "Documentation":
        return False
    notes = row["notes"].lower()
    markers = (
        "treated as documentation",
        "parent openfoam software ecosystem",
        "parent project",
        "links the openfoam gplv3 software license",
        "point back to the openfoam gplv3 software license",
        "rather than as a standalone code artifact",
        "rather than as unresolved standalone-license debt",
    )
    return any(marker in notes for marker in markers)


def paper_evidence_status(row: dict[str, str]) -> str:
    if has_link(row["paper_url"]):
        return "Direct paper link"

    notes = row["notes"].lower()
    if "public citation text verified" in notes:
        return "Citation text verified, URL unresolved"
    if "project-level citation evidence verified" in notes:
        return "Project citation database only"
    return "No public paper evidence surfaced"


def scope_alignment(row: dict[str, str]) -> str:
    category = base_category(row["category"])
    text = " ".join([row["regime"], row["workflow"], row["notes"]]).lower()

    if category == "Adjacent or name-collision projects":
        return "Name-collision guardrail"
    if "less directly focused" in text or "transferable benchmark only after bubble-specific validation" in text:
        return "Peripheral or transfer-only"
    if category in {
        "Datasets",
        "Optical imaging and computer vision",
        "Reduced-order bubble dynamics",
        "Acoustics and sequence regression",
        "Scientific machine learning",
    }:
        return "Core bubble/boiling"
    if category == "Simulation and ML benchmarks":
        return "Core bubble/boiling" if "boiling" in text or "bubble" in text else "Peripheral or transfer-only"
    if category == "CFD and multiphase simulation":
        peripheral_markers = (
            "gas-solid multiphase",
            "fluidized beds",
            "general engineering geometries",
        )
        if any(marker in text for marker in peripheral_markers):
            return "Peripheral or transfer-only"
        if any(marker in text for marker in ("bubble", "boiling", "cavitation", "free-surface", "vof", "multiphase")):
            return "Adjacent but directly useful"
    if category == "General image and flow utilities":
        return "Adjacent but directly useful"
    return "Adjacent but directly useful"


def scope_weight(row: dict[str, str]) -> int:
    alignment = scope_alignment(row)
    if alignment == "Core bubble/boiling":
        return 6
    if alignment == "Adjacent but directly useful":
        return 3
    if alignment == "Peripheral or transfer-only":
        return -12
    return 0


def review_priority(row: dict[str, str]) -> list[str]:
    issues: list[str] = []
    if row["status"] == "review sharing":
        issues.append("sharing link")
    if (
        license_bucket(row) in {"Manual license review", "Unclear license"}
        and not documentation_license_context(row)
    ):
        issues.append("license check")
    if row["kind"] in {"Code", "Code and dataset", "Model artifact", "Dataset"}:
        evidence = paper_evidence_status(row)
        if evidence == "No public paper evidence surfaced":
            issues.append("no paper evidence")
        elif evidence != "Direct paper link":
            issues.append("paper URL unresolved")
    return issues


def maintenance_blocker(row: dict[str, str]) -> str:
    if row["status"] == "review sharing":
        return "access/link stability"

    if paper_evidence_status(row) in {
        "Citation text verified, URL unresolved",
        "Project citation database only",
    }:
        return "citation discoverability"

    notes = row["notes"].lower()
    upstream_markers = (
        "no explicit license",
        "no associated paper link",
        "no linked paper",
        "no public paper link",
        "did not expose",
        "did not surface",
        "no stable paper url",
        "no linked publication",
        "no software citation",
        "no license file",
        "no stable thesis or paper url",
        "no standalone spdx-style license file",
        "no repository-level license badge",
        "not exposed on the public",
        "still shows no explicit license",
        "remains absent from the public",
    )
    if any(marker in notes for marker in upstream_markers):
        return "upstream sparsity"

    if review_priority(row):
        return "catalog backfill"
    return "none"


def review_focus_counts(rows: Iterable[dict[str, str]]) -> list[tuple[str, int]]:
    counts: Counter[str] = Counter()
    for row in active_rows(rows):
        counts.update(review_priority(row))
    return sorted(counts.items(), key=lambda item: (-item[1], item[0]))


def blocker_counts(rows: Iterable[dict[str, str]]) -> list[tuple[str, int]]:
    counts: Counter[str] = Counter()
    for row in active_rows(rows):
        blocker = maintenance_blocker(row)
        if blocker != "none":
            counts[blocker] += 1
    return sorted(counts.items(), key=lambda item: (-item[1], item[0]))


def review_focus_by_category(rows: Iterable[dict[str, str]]) -> list[dict[str, object]]:
    grouped: dict[str, Counter[str]] = defaultdict(Counter)
    for row in active_rows(rows):
        category = base_category(row["category"])
        for issue in review_priority(row):
            grouped[category][issue] += 1

    issue_order = ["no paper evidence", "paper URL unresolved", "license check", "sharing link"]
    results: list[dict[str, object]] = []
    for category, counts in grouped.items():
        total = sum(counts.values())
        results.append(
            {
                "category": category,
                "total": total,
                "counts": {issue: counts.get(issue, 0) for issue in issue_order},
            }
        )
    return sorted(results, key=lambda item: (-int(item["total"]), str(item["category"])))


def blocker_by_category(rows: Iterable[dict[str, str]]) -> list[dict[str, object]]:
    grouped: dict[str, Counter[str]] = defaultdict(Counter)
    blocker_order = [
        "catalog backfill",
        "citation discoverability",
        "upstream sparsity",
        "access/link stability",
    ]
    for row in active_rows(rows):
        blocker = maintenance_blocker(row)
        if blocker == "none":
            continue
        grouped[base_category(row["category"])][blocker] += 1

    results: list[dict[str, object]] = []
    for category, counts in grouped.items():
        total = sum(counts.values())
        results.append(
            {
                "category": category,
                "total": total,
                "counts": {blocker: counts.get(blocker, 0) for blocker in blocker_order},
            }
        )
    return sorted(results, key=lambda item: (-int(item["total"]), str(item["category"])))


def days_since_checked(row: dict[str, str]) -> int:
    return (date.today() - date.fromisoformat(row["source_checked"])).days


def priority_frontier(
    rows: Iterable[dict[str, str]],
    limit: int = 12,
    blocker_filter: str | None = None,
) -> list[dict[str, object]]:
    category_issue_totals = {
        str(item["category"]): int(item["total"]) for item in review_focus_by_category(rows)
    }
    ranked: list[dict[str, object]] = []
    for row in active_rows(rows):
        issues = review_priority(row)
        if not issues:
            continue
        category = base_category(row["category"])
        blocker = maintenance_blocker(row)
        if blocker_filter and blocker != blocker_filter:
            continue
        score = (
            len(issues) * 10
            + category_issue_totals.get(category, 0) * 2
            + days_since_checked(row)
            + scope_weight(row)
        )
        ranked.append(
            {
                "row": row,
                "category": category,
                "issues": issues,
                "blocker": blocker,
                "scope": scope_alignment(row),
                "days_stale": days_since_checked(row),
                "score": score,
            }
        )
    ranked.sort(
        key=lambda item: (
            -int(item["score"]),
            -len(list(item["issues"])),
            -int(item["days_stale"]),
            str(item["row"]["name"]).lower(),
        )
    )
    return ranked[:limit]


def has_paper_link(row: dict[str, str]) -> bool:
    return has_link(row["paper_url"])


def has_verified_paper_evidence(row: dict[str, str]) -> bool:
    return paper_evidence_status(row) != "No public paper evidence surfaced"


def clarified_license(row: dict[str, str]) -> bool:
    if documentation_license_context(row):
        return True
    return license_bucket(row) not in {"Archive/model terms", "Manual license review", "Unclear license"}


def coverage_stats(rows: Iterable[dict[str, str]]) -> list[dict[str, object]]:
    grouped: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in active_rows(rows):
        grouped[base_category(row["category"])].append(row)

    stats: list[dict[str, object]] = []
    for category, items in grouped.items():
        entry_count = len(items)
        paper_count = sum(has_paper_link(row) for row in items)
        verified_paper_count = sum(has_verified_paper_evidence(row) for row in items)
        license_count = sum(clarified_license(row) for row in items)
        open_license_count = sum(license_bucket(row) == "Explicit open license" for row in items)
        restrictive_license_count = sum(license_bucket(row) == "Explicit restrictive terms" for row in items)
        strong_evidence = sum(
            evidence_tier(row) in {"Code + data + paper", "Dataset + paper", "Code + paper/docs"}
            for row in items
        )
        stats.append(
            {
                "category": category,
                "entries": entry_count,
                "paper_count": paper_count,
                "paper_share": paper_count / entry_count,
                "verified_paper_count": verified_paper_count,
                "verified_paper_share": verified_paper_count / entry_count,
                "license_count": license_count,
                "license_share": license_count / entry_count,
                "open_license_count": open_license_count,
                "restrictive_license_count": restrictive_license_count,
                "strong_evidence": strong_evidence,
            }
        )
    return sorted(stats, key=lambda item: (-int(item["entries"]), str(item["category"])))


def reduced_order_readiness(row: dict[str, str]) -> str:
    issues = review_priority(row)
    paper_state = paper_evidence_status(row)

    if not issues:
        return "Reference-backed"
    if paper_state != "No public paper evidence surfaced" and "license check" in issues:
        return "Paper-backed, license unclear"
    if paper_state == "No public paper evidence surfaced" and "license check" in issues:
        return "Prototype-only"
    if paper_state == "No public paper evidence surfaced":
        return "Code-backed, paper sparse"
    return "Needs targeted review"


