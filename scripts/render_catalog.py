    ax.set_yticks(range(len(categories)), labels=categories)
    ax.set_title("Modality Coverage by Workflow Category")
    for row_index, row_values in enumerate(matrix):
        for col_index, value in enumerate(row_values):
            if value:
                ax.text(col_index, row_index, str(value), ha="center", va="center", fontsize=8)
    fig.colorbar(image, ax=ax, label="Entries")
    save_figure(fig, "modality_heatmap")


